#!/usr/bin/env bash
#
# Remove the al-folio demo content that the Vidaurre Lab site does not use.
#
# The site already builds correctly without running this: the demo pages and
# collection entries are stubbed out with `published: false`, and the blog,
# archives and demo posts are switched off in _config.yml. This script is the
# tidy-up — it deletes those files for real so the repository stops carrying
# ~30 Einstein-era example posts and their assets.
#
# Run once, from the repository root, then review with `git status` before
# committing:
#
#   bash bin/cleanup-demo-content.sh
#
set -euo pipefail

cd "$(dirname "$0")/.."

if [ ! -f _config.yml ]; then
  echo "error: run this from the repository root" >&2
  exit 1
fi

remove() {
  for path in "$@"; do
    if [ -e "$path" ]; then
      if git ls-files --error-unmatch "$path" >/dev/null 2>&1; then
        git rm -r -q "$path"
      else
        rm -rf "$path"
      fi
      echo "removed $path"
    fi
  done
}

echo "== demo blog posts =="
remove _posts
remove assets/jupyter/blog.ipynb assets/plotly/demo.html assets/html/relativity.html
remove assets/json/table_data.json assets/audio assets/video/pexels-engin-akyurt-6069112-960x540-30fps.mp4
remove assets/bibliography/2018-12-22-distill.bib

echo "== demo pages =="
remove _pages/blog.md _pages/books.md _pages/cv.md _pages/dropdown.md
remove _pages/plugins.md _pages/profiles.md _pages/repositories.md _pages/teaching.md
remove _pages/about_einstein.md

echo "== demo collections =="
remove _books _teachings
remove _projects/5_project.md _projects/6_project.md _projects/7_project.md
remove _projects/8_project.md _projects/9_project.md

echo "== demo assets =="
remove assets/img/prof_pic.jpg assets/img/prof_pic_color.png assets/img/rhino.png
remove assets/img/book_covers assets/img/publication_preview
remove assets/img/1.jpg assets/img/2.jpg assets/img/3.jpg assets/img/4.jpg assets/img/5.jpg
remove assets/img/6.jpg assets/img/7.jpg assets/img/8.jpg assets/img/9.jpg
remove assets/img/10.jpg assets/img/11.jpg assets/img/12.jpg
remove assets/pdf/example_pdf.pdf

cat <<'NOTE'

Done. Deliberately left in place:

  * assets/json/resume.json and _data/cv.yml — _config.yml's `jekyll_get_json`
    block still points at resume.json. Remove that block from _config.yml first
    if you want these gone.
  * readme_preview/ and lighthouse_results/ — referenced by the upstream README.
  * _data/citations.yml — the al-folio citation cache, regenerated by
    bin/update_scholar_citations.py.

Now run:

    npx prettier . --write
    bundle exec jekyll build

NOTE
